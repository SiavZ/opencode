//! Purpose: generate portable Rust client operations from the authoritative Protocol registry.
//! Scope: build-time Rust output only, never writes into packages.
//! Uses:
//! `-- rust/xtask/src/codegen/{emit,types,writer}.rs
//! External:
//! |-- anyhow
//! `-- opencode_protocol
//! Used by:
//! `-- rust/xtask/src/lib.rs
//! Invariants: generation is deterministic; checks never mutate output.
//! Contract tests: xtask/tests/codegen.rs
mod emit;
mod format;
mod types;
mod writer;

use anyhow::{Result, bail};
use std::collections::BTreeMap;
use std::path::Path;

pub trait Source {
    fn apis(&self) -> Vec<(&str, &opencode_protocol::Api)>;
}
pub struct Protocol;
impl Source for Protocol {
    fn apis(&self) -> Vec<(&str, &opencode_protocol::Api)> {
        vec![
            ("current", opencode_protocol::current::api()),
            ("legacy", opencode_protocol::legacy::api()),
        ]
    }
}

pub fn generate(source: &impl Source) -> Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    files.insert(
        "mod.rs".into(),
        header("generated client API root") + "pub mod current;\npub mod legacy;\n",
    );
    for (name, api) in source.apis() {
        if !matches!(name, "current" | "legacy") {
            bail!("unsupported client namespace: {name}");
        }
        emit::api(name, api, &mut files)?;
    }
    format::format(files)
}

pub fn write(root: &Path, files: &BTreeMap<String, String>, check: bool) -> Result<()> {
    writer::write(root, files, check)
}

pub fn run(args: &[String]) -> Result<()> {
    if args.iter().any(|arg| arg != "--check") {
        bail!("usage: cargo xtask codegen [--check]");
    }
    write(
        &crate::workspace::rust_root()?.join("crates/client/src/generated"),
        &generate(&Protocol)?,
        args.iter().any(|arg| arg == "--check"),
    )
}

pub(super) fn header(purpose: &str) -> String {
    format!(
        "//! Purpose: {purpose}.\n//! Scope: generated portable client values.\n//! Uses:\n//! `-- rust/crates/client/src/operation.rs\n//! External:\n//! |-- serde\n//! `-- serde_json\n//! Used by:\n//! `-- rust/crates/client/src/lib.rs\n//! Invariants: generated by cargo xtask codegen; do not edit.\n//! Contract tests: client/tests/operations.rs, xtask/tests/codegen.rs\n\n"
    )
}

pub(super) fn snake(value: &str) -> String {
    let chars = value.chars().collect::<Vec<_>>();
    let mut output = String::new();
    for (index, c) in chars.iter().copied().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !output.ends_with('_') {
                output.push('_');
            }
            continue;
        }
        if c.is_ascii_uppercase()
            && index > 0
            && (chars[index - 1].is_ascii_lowercase()
                || chars[index - 1].is_ascii_digit()
                || chars[index - 1].is_ascii_uppercase()
                    && chars.get(index + 1).is_some_and(char::is_ascii_lowercase))
            && !output.ends_with('_')
        {
            output.push('_');
        }
        output.push(c.to_ascii_lowercase());
    }
    let output = output.trim_matches('_').to_owned();
    if [
        "type", "ref", "self", "super", "crate", "mod", "move", "match", "loop", "async", "await",
        "use", "fn", "in", "where", "struct", "enum", "const", "static", "impl", "trait", "pub",
        "return", "continue", "break", "for", "if", "else", "let", "mut", "dyn", "as", "box",
        "try", "yield", "abstract", "become", "do", "final", "macro", "override", "priv", "typeof",
        "unsized", "virtual",
    ]
    .contains(&output.as_str())
    {
        format!("{output}_")
    } else if output.starts_with(char::is_numeric) {
        format!("n_{output}")
    } else {
        output
    }
}
pub(super) fn pascal(value: &str) -> String {
    snake(value)
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string())
                .unwrap_or_default()
                + chars.as_str()
        })
        .collect()
}
